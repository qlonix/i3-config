#!/bin/bash

# ==========================================
# i3wm ロック画面ラッパースクリプト
# 壁紙付き・視認性の高いロック画面を起動します
# ==========================================

LOCK_IMG="$HOME/.config/i3/lockscreen.png"

# ロック画面用画像が存在すれば画像付きで起動、なければテーマ色で起動
# -e: 空のパスワードでのアンロック試行を無視
# -n: フォークせずフォアグラウンドで待機 (xss-lockとの連携に必須)
if [ -f "$LOCK_IMG" ]; then
    exec i3lock -n -i "$LOCK_IMG" -e
else
    exec i3lock -n -c 1E1E2E -e
fi
